-- Ao excluir um usuário: ocorrências, categorias e histórico perdem a referência (SET NULL);
-- assinaturas (dado pessoal sem valor operacional) são apagadas (CASCADE).

-- Ocorrências: autor opcional
ALTER TABLE occurrences ALTER COLUMN owner_id DROP NOT NULL;
ALTER TABLE occurrences DROP CONSTRAINT fkm0l5p8ar9jv2lat213qua8fj3;
ALTER TABLE occurrences ADD CONSTRAINT fk_occurrences_owner
    FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE SET NULL;
CREATE INDEX idx_occurrences_owner_id ON occurrences(owner_id);

-- Categorias: criador opcional
ALTER TABLE types ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE types DROP CONSTRAINT fke9jhleoesq8lrvbefjx4o7hh;
ALTER TABLE types ADD CONSTRAINT fk_types_user
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL;

-- Assinaturas: removidas junto com o usuário
ALTER TABLE subscriptions DROP CONSTRAINT fkoodc4352epkjrvxx79odlxbji;
ALTER TABLE subscriptions ADD CONSTRAINT fk_subscriptions_subscriber
    FOREIGN KEY (subscriber_id) REFERENCES users(id) ON DELETE CASCADE;

-- Histórico de status das ocorrências
CREATE TABLE occurrence_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurrence_id BIGINT NOT NULL,
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    reason TEXT,
    changed_by UUID,
    changed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_status_history_occurrence
        FOREIGN KEY (occurrence_id) REFERENCES occurrences(id) ON DELETE CASCADE,
    CONSTRAINT fk_status_history_changed_by
        FOREIGN KEY (changed_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_status_history_occurrence_id ON occurrence_status_history(occurrence_id);
CREATE INDEX idx_status_history_changed_by ON occurrence_status_history(changed_by);

-- Backfill: evento de criação para as ocorrências existentes (somente INSERT)
